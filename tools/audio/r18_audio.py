"""Round 18 audio: a bank of single notes for the judgement tunes (FluidSynth + GeneralUser GS) and a few soft new sound effects.

    python tools/audio/r18_audio.py            # everything
    python tools/audio/r18_audio.py notes      # only the note bank  -> game/assets/audio/notes/<instrument>_<midi>.ogg
    python tools/audio/r18_audio.py sfx        # only the sound effects -> game/assets/audio/sfx/*.wav (+ audio_names.gd)

The game plays a tune by playing the nearest sample of an instrument, pitch-shifted by at most two semitones (scripts/systems/tunes.gd, audio_manager.gd play_note).
Nothing here is loud: the judgements are a game of listening, and the players asked for gentle sounds.
"""
import os, sys, re
import numpy as np
import synth
from synth import SR
import midi_util
import sf_render

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.abspath(os.path.join(HERE, "..", "..", "game"))
NOTE_DIR = os.path.join(GAME, "assets", "audio", "notes")
SFX_DIR = os.path.join(GAME, "assets", "audio", "sfx")
NAMES_GD = os.path.join(GAME, "scripts", "systems", "audio_names.gd")

# name -> (GM program, note length in seconds, volume cc, reverb send)
INSTRUMENTS = {
    "marimba": (12, 1.1, 110, 28),
    "musicbox": (10, 1.5, 112, 34),
    "kalimba": (108, 1.2, 112, 30),
    "harp": (46, 1.9, 108, 36),
    "celesta": (8, 1.7, 112, 36),
    "glock": (9, 1.3, 104, 30),
    "pad": (89, 2.6, 96, 45),
    "tinkle": (112, 1.1, 100, 28),     # round 18b: the bright 'ting' that sits on top of every good press
    "xylo": (13, 0.9, 112, 22),        # round 18b: a plucky, bright voice for the hits of the rhythm game
}
MIDIS = [55, 58, 61, 64, 67, 70, 73, 76, 79, 82, 85, 88, 91, 94, 97, 100]
# round 18b: the players found the click not bright enough: a high shelf (dB above ~2.2 kHz) for the plucked / struck voices, so that the first 30 ms 'tick' of every note speaks
BRIGHT = {"marimba": 6.0, "musicbox": 5.0, "kalimba": 6.0, "harp": 4.0, "celesta": 4.0, "glock": 3.0, "tinkle": 2.0, "xylo": 5.0}


def render_note(inst, m):
    prog, ln, vol, rev = INSTRUMENTS[inst]
    sc = midi_util.Score(60)
    tr = sc.track(prog, vol=vol, reverb=rev)
    sc.add(tr, 0.0, ln * 0.92, m, 88)
    x, sr = sf_render.render_wav(sc, "r18_%s_%d" % (inst, m), gain=0.85, reverb=(0.4, 0.4, 0.8, 0.35))
    mono = x.mean(axis=1)
    if sr != SR:
        raise SystemExit("unexpected sample rate %d" % sr)
    n = int((ln + 0.35) * SR)
    mono = mono[:n] if len(mono) >= n else np.pad(mono, (0, n - len(mono)))
    # the tail dies away on its own: a gentle cosine fade over the last 40 %
    nf = int(0.4 * n)
    mono[-nf:] *= 0.5 * (1 + np.cos(np.linspace(0, np.pi, nf)))
    mono = synth.hp(mono, 60, 1)
    if inst in BRIGHT:
        g = 10 ** (BRIGHT[inst] / 20.0) - 1.0
        mono = mono + g * synth.hp(mono, 2200, 2)
    # one loudness for every note: the RMS of the first half second sits at -21 dBFS (pitch-shifting changes nothing about that)
    head = mono[: int(0.5 * SR)]
    r = np.sqrt(np.mean(head ** 2)) + 1e-9
    mono = mono * (10 ** (-21.0 / 20.0) / r)
    pk = np.max(np.abs(mono))
    if pk > 0.9:
        mono = mono * (0.9 / pk)
    return mono


def notes():
    os.makedirs(NOTE_DIR, exist_ok=True)
    for inst in INSTRUMENTS:
        for m in MIDIS:
            x = render_note(inst, m)
            synth.write_ogg(x, os.path.join(NOTE_DIR, "%s_%d.ogg" % (inst, m)), quality=4)
        print("notes", inst, flush=True)
    # the lists the game reads (generated)
    with open(os.path.join(GAME, "scripts", "systems", "note_names.gd"), "w", newline="\n") as f:
        f.write("# GENERATED by tools/audio/r18_audio.py - do not edit\n")
        f.write("const INSTS = [%s]\n" % ", ".join('"%s"' % k for k in INSTRUMENTS))
        f.write("const MIDIS = [%s]\n" % ", ".join(str(m) for m in MIDIS))


# ------------------------------------------------------------------ sound effects
def env_exp(n, tau, attack=0.004):
    t = np.arange(n) / SR
    return np.exp(-t / tau) * np.minimum(t / attack, 1.0)


def soft_bump():
    """a wall or a ball against a feather pillow: a low round thump and a puff of air, no edge at all (the old crash sounds were harsh)"""
    n = int(0.45 * SR)
    t = np.arange(n) / SR
    f = 120.0 * np.exp(-t * 7.0) + 52.0
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * env_exp(n, 0.07, 0.006)
    puff = synth.lp(synth.noise(n, "pink"), 900, 2) * env_exp(n, 0.09, 0.012) * 0.55
    x = body * 0.9 + puff
    x = synth.softclip(x * 0.8, 1.2)
    return synth.fade(synth.normalize(x, 0.5), 0.004, 0.08)


def soft_hit():
    """the friendly 'oof' of a bump in the town: shorter than the bump and a little higher"""
    n = int(0.3 * SR)
    t = np.arange(n) / SR
    f = 190.0 * np.exp(-t * 9.0) + 75.0
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * env_exp(n, 0.05, 0.005)
    puff = synth.lp(synth.noise(n, "pink"), 1200, 2) * env_exp(n, 0.05, 0.008) * 0.4
    return synth.fade(synth.normalize(body * 0.9 + puff, 0.45), 0.003, 0.06)


def count_tick():
    """the count-in before the slow first wave: a soft wooden tick, round, never sharp"""
    n = int(0.16 * SR)
    t = np.arange(n) / SR
    x = np.sin(2 * np.pi * 760.0 * t) * np.exp(-t / 0.028) + 0.35 * np.sin(2 * np.pi * 1520.0 * t) * np.exp(-t / 0.014)
    x += synth.lp(synth.noise(n), 2400, 2) * np.exp(-t / 0.006) * 0.25
    x *= np.minimum(t / 0.002, 1.0)
    return synth.fade(synth.normalize(x, 0.55), 0.001, 0.05)


def ready_chime():
    """the 'now you can' sound when a locked judgement starts: two soft rising notes"""
    out = np.zeros(int(0.7 * SR))
    for i, m in enumerate([76, 83]):
        n = int(0.5 * SR)
        t = np.arange(n) / SR
        x = (np.sin(2 * np.pi * synth.hz(m) * t) + 0.25 * np.sin(2 * np.pi * synth.hz(m) * 2.0 * t)) * np.exp(-t / 0.16) * np.minimum(t / 0.004, 1.0)
        synth.mix_into(out, x, 0.07 * i, 0.45)
    return synth.fade(synth.normalize(out, 0.45), 0.002, 0.1)


def hello():
    """a small, warm two-note 'hello' (a friend turned up)"""
    out = np.zeros(int(0.6 * SR))
    for i, m in enumerate([79, 84]):
        n = int(0.45 * SR)
        t = np.arange(n) / SR
        x = (np.sin(2 * np.pi * synth.hz(m) * t) + 0.2 * np.sin(2 * np.pi * synth.hz(m) * 3.0 * t)) * np.exp(-t / 0.2) * np.minimum(t / 0.006, 1.0)
        synth.mix_into(out, x, 0.12 * i, 0.4)
    return synth.fade(synth.normalize(out, 0.4), 0.003, 0.12)


def friend_welcome():
    """ROUND 18b: a friend gull lands next to you. The cue the players asked for: warm, playful, 'you are welcome here'. 126 bpm, C major, two bars (I - IV - V - I) and a sparkling
    landing: a harp run as the friend swoops in, a music-box tune that skips up to a high note, plucked strings that bounce on the off-beats, a harp bed, a soft pad and (at the
    end) a choir 'aah' that swells under the last chord, then a little run of tinkling bells. ~4.5 s."""
    sc = midi_util.Score(126)
    mel = sc.track(10, vol=112, pan=64, reverb=40)         # music box: the tune
    mel2 = sc.track(8, vol=88, pan=70, reverb=40)          # celesta: the same tune an octave up, softer: the sparkle
    harp = sc.track(46, vol=104, pan=50, reverb=38)        # the bed of broken chords
    pizz = sc.track(45, vol=92, pan=78, reverb=26)         # bouncing stabs on the off-beats
    pad = sc.track(89, vol=78, pan=64, reverb=55)          # the warm cushion
    choir = sc.track(52, vol=70, pan=64, reverb=60)        # 'aah'
    bells = sc.track(112, vol=96, pan=60, reverb=44)       # tinkling run at the end
    o = 0.5                                                # the swoop-in comes first
    # the swoop: a harp run up two octaves, over half a beat
    run = [60, 64, 67, 72, 76, 79, 84]
    for k, m in enumerate(run):
        sc.add(harp, k * (o / len(run)), 0.5, m, 70 + 3 * k)
    # the tune (beats from o): pick-up, then skipping up to a high, held note
    tune = [(0.0, 0.5, 76), (0.5, 0.5, 79), (1.0, 1.0, 84), (2.0, 0.5, 81), (2.5, 0.5, 77), (3.0, 1.0, 81),
            (4.0, 0.5, 79), (4.5, 0.5, 83), (5.0, 1.0, 86), (6.0, 0.5, 84), (6.5, 0.5, 88), (7.0, 2.5, 91)]
    for b, d, m in tune:
        sc.add(mel, o + b, d * 0.95 + 0.2, m, 92)
        sc.add(mel2, o + b, d * 0.9 + 0.1, m + 12 if m + 12 <= 100 else m, 52)
    # the chords: C - F - G - C, two beats each
    chords = [(0.0, [48, 55, 64]), (2.0, [53, 57, 65]), (4.0, [55, 59, 67]), (6.0, [48, 55, 64])]
    for b, ch in chords:
        for k, m in enumerate([ch[0], ch[1] + 12, ch[2] + 12, ch[1] + 12]):
            sc.add(harp, o + b + k * 0.5, 0.9, m, 64 if k else 74)
        for m in ch:
            sc.add(pad, o + b, 2.2, m, 50)
        for q in (0.5, 1.5):
            for m in ch[1:]:
                sc.add(pizz, o + b + q, 0.25, m + 12, 58)
    # the last chord swells: a choir under the held note
    for m in [60, 64, 67, 72]:
        sc.add(choir, o + 6.0, 3.4, m, 58)
    # a run of tinkling bells on top of the last note (C major pentatonic, upward)
    for k, m in enumerate([84, 88, 91, 93, 96, 100]):
        sc.add(bells, o + 7.0 + 0.25 * k, 1.2, m, 60 + 4 * k)
    x, sr = sf_render.render_wav(sc, "r18_friend_welcome", gain=0.85, reverb=(0.5, 0.35, 0.9, 0.4))
    x = sf_render.finish(x, fade_out=0.5) if hasattr(sf_render, "finish") else x
    mono = x.mean(axis=1)
    mono = mono + (10 ** (3.0 / 20.0) - 1.0) * synth.hp(mono, 2500, 2)
    mono = synth.fade(synth.normalize(mono, 0.6), 0.003, 0.4)
    return mono


SOUNDS = {"friend_welcome": friend_welcome, "soft_bump": soft_bump, "soft_hit": soft_hit, "count_tick": count_tick, "ready_chime": ready_chime, "hello": hello}


def sfx():
    os.makedirs(SFX_DIR, exist_ok=True)
    for n, fn in SOUNDS.items():
        synth.write_wav(np.nan_to_num(fn()), os.path.join(SFX_DIR, n + ".wav"))
        print("sfx", n, flush=True)
    # add the names to the list the game loads (the list is generated by render_sfx.py, which would also rewrite the music list: so it is patched here instead)
    src = open(NAMES_GD, encoding="utf-8").read()
    m = re.search(r"const SFX = \[(.*?)\]", src, re.S)
    have = re.findall(r'"([^"]+)"', m.group(1))
    allnames = sorted(set(have) | set(SOUNDS.keys()))
    new = "const SFX = [" + ", ".join('"%s"' % n for n in allnames) + "]"
    src = src[: m.start()] + new + src[m.end():]
    with open(NAMES_GD, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)


if __name__ == "__main__":
    what = sys.argv[1:] or ["sfx", "notes"]
    if "sfx" in what:
        sfx()
    if "notes" in what:
        notes()
